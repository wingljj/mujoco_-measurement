"""Build paper figures for the theodolite attitude-constrained study.

The script consumes one or more experiment result CSV files generated by
simulate_transport.py. It focuses on the journal claims needed for the paper:
constraint satisfaction, terminal accuracy, and joint-space smoothness.
"""

from __future__ import annotations

import argparse
import csv
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Sequence

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np
from matplotlib import font_manager as fm


DPI = 360
POSITION_TOLERANCE_M = 0.02
DEFAULT_TILT_LIMIT_DEG = 45.0
CHINESE_FONT = fm.FontProperties(fname=r"C:\Windows\Fonts\STSONG.TTF")
LATIN_FONT = fm.FontProperties(fname=r"C:\Windows\Fonts\times.ttf")
LATIN_BOLD_FONT = fm.FontProperties(fname=r"C:\Windows\Fonts\timesbd.ttf")
COLORS = {
    "blue": "#2F5597",
    "orange": "#C55A11",
    "green": "#548235",
    "red": "#A61C1C",
    "gray": "#666666",
    "light_gray": "#D9D9D9",
    "purple": "#7030A0",
}
METHOD_LABELS = {
    "proposed": "本文方法",
    "position_only": "仅位置逆解",
    "joint_linear": "关节空间插值",
}


@dataclass(frozen=True)
class Experiment:
    label: str
    rows: List[Dict[str, object]]
    results_path: Path
    trajectories_path: Path | None


def configure_style() -> None:
    mpl.rcParams.update(
        {
            "font.family": "Times New Roman",
            "font.serif": ["Times New Roman"],
            "font.sans-serif": ["STSong"],
            "font.size": 8.5,
            "axes.labelsize": 8.5,
            "axes.titlesize": 9.0,
            "legend.fontsize": 7.4,
            "xtick.labelsize": 7.4,
            "ytick.labelsize": 7.4,
            "axes.linewidth": 0.8,
            "grid.linewidth": 0.4,
            "lines.linewidth": 1.35,
            "lines.markersize": 4.0,
            "figure.dpi": DPI,
            "savefig.dpi": DPI,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "mathtext.fontset": "custom",
            "mathtext.rm": "Times New Roman",
            "mathtext.it": "Times New Roman:italic",
            "mathtext.bf": "Times New Roman:bold",
            "axes.unicode_minus": False,
        }
    )


def has_cjk(text: str) -> bool:
    return any("\u4e00" <= char <= "\u9fff" for char in text)


def apply_publication_fonts(fig: plt.Figure) -> None:
    """Use SimSun for Chinese text and Times New Roman for western/numeric text."""

    for text in fig.findobj(match=mpl.text.Text):
        value = text.get_text()
        if not value:
            continue
        text.set_fontproperties(CHINESE_FONT if has_cjk(value) else LATIN_FONT)
    for ax in fig.axes:
        for spine in ax.spines.values():
            spine.set_linewidth(0.8)
        tick_labels = ax.get_xticklabels() + ax.get_yticklabels()
        if hasattr(ax, "get_zticklabels"):
            tick_labels += ax.get_zticklabels()
        for tick in tick_labels:
            value = tick.get_text()
            tick.set_fontproperties(CHINESE_FONT if has_cjk(value) else LATIN_FONT)


def read_results(path: Path, label: str | None = None) -> Experiment:
    rows: List[Dict[str, object]] = []
    with path.open("r", newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for raw in reader:
            method = raw.get("method", label or infer_label(path))
            rows.append(
                {
                    "method": method,
                    "target_id": int(raw["target_id"]),
                    "target": np.asarray(
                        [
                            float(raw["target_x"]),
                            float(raw["target_y"]),
                            float(raw["target_z"]),
                        ],
                        dtype=float,
                    ),
                    "planned_success": parse_bool(raw.get("planned_success", raw.get("reachable", ""))),
                    "sim_success": parse_bool(raw.get("sim_success", "")),
                    "final_error_m": parse_float(raw.get("final_error_m", "nan")),
                    "planned_error_m": parse_float(raw.get("planned_error_m", "nan")),
                    "max_tilt_deg": parse_float(raw.get("max_tilt_deg", "nan")),
                    "planned_max_tilt_deg": parse_float(raw.get("planned_max_tilt_deg", "nan")),
                    "path_length_m": parse_float(raw.get("path_length_m", "nan")),
                    "joint_path_length_rad": parse_float(raw.get("joint_path_length_rad", "nan")),
                    "mean_joint_step_rad": parse_float(raw.get("mean_joint_step_rad", "nan")),
                    "max_joint_step_rad": parse_float(raw.get("max_joint_step_rad", "nan")),
                    "rms_joint_speed_rad_s": parse_float(raw.get("rms_joint_speed_rad_s", "nan")),
                    "max_joint_speed_rad_s": parse_float(raw.get("max_joint_speed_rad_s", "nan")),
                    "rms_joint_accel_rad_s2": parse_float(raw.get("rms_joint_accel_rad_s2", "nan")),
                    "max_joint_accel_rad_s2": parse_float(raw.get("max_joint_accel_rad_s2", "nan")),
                }
            )
    method_name = label or str(rows[0]["method"] if rows else infer_label(path))
    trajectories_path = path.parent / "trajectories.npz"
    if not trajectories_path.exists():
        trajectories_path = None
    return Experiment(
        label=METHOD_LABELS.get(method_name, method_name),
        rows=rows,
        results_path=path,
        trajectories_path=trajectories_path,
    )


def infer_label(path: Path) -> str:
    stem = path.parent.name.lower()
    for key in METHOD_LABELS:
        if key in stem:
            return key
    return stem


def parse_bool(value: object) -> bool:
    return str(value).strip().lower() in {"true", "1", "yes", "y"}


def parse_float(value: object) -> float:
    try:
        return float(str(value))
    except ValueError:
        return float("nan")


def finite_values(rows: Sequence[Dict[str, object]], key: str) -> np.ndarray:
    values = np.asarray([float(row[key]) for row in rows], dtype=float)
    return values[np.isfinite(values)]


def successful_rows(rows: Sequence[Dict[str, object]]) -> List[Dict[str, object]]:
    return [row for row in rows if bool(row["sim_success"])]


def save(fig: plt.Figure, out_dir: Path, name: str) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    apply_publication_fonts(fig)
    fig.savefig(out_dir / f"{name}.png", bbox_inches="tight", facecolor=fig.get_facecolor())
    fig.savefig(out_dir / f"{name}.pdf", bbox_inches="tight", facecolor=fig.get_facecolor())
    print(f"saved {out_dir / f'{name}.png'} and {out_dir / f'{name}.pdf'}")


def plot_sampling_constraint_3d(exp: Experiment, out_dir: Path, tilt_limit: float) -> None:
    rows = exp.rows
    targets = np.asarray([row["target"] for row in rows], dtype=float)
    planned = np.asarray([bool(row["planned_success"]) for row in rows], dtype=bool)
    final_error = np.asarray([float(row["final_error_m"]) for row in rows], dtype=float)
    max_tilt = np.asarray([float(row["max_tilt_deg"]) for row in rows], dtype=float)
    accurate = np.isfinite(final_error) & (final_error <= POSITION_TOLERANCE_M)
    tilt_safe = np.isfinite(max_tilt) & (max_tilt <= tilt_limit)
    success = planned & accurate & tilt_safe
    tilt_violation = planned & accurate & ~tilt_safe
    tracking_or_ik_fail = ~success & ~tilt_violation

    fig = plt.figure(figsize=(6.8, 5.2), facecolor="white")
    ax = fig.add_subplot(111, projection="3d")
    if np.any(tracking_or_ik_fail):
        ax.scatter(
            targets[tracking_or_ik_fail, 0],
            targets[tracking_or_ik_fail, 1],
            targets[tracking_or_ik_fail, 2],
            s=42,
            marker="x",
            color=COLORS["gray"],
            linewidths=1.4,
            label="规划/跟踪失败",
            depthshade=False,
        )
    if np.any(tilt_violation):
        ax.scatter(
            targets[tilt_violation, 0],
            targets[tilt_violation, 1],
            targets[tilt_violation, 2],
            s=48,
            marker="^",
            color=COLORS["red"],
            edgecolors="#111111",
            linewidths=0.3,
            label="倾角越界",
            depthshade=False,
        )
    if np.any(success):
        scatter = ax.scatter(
            targets[success, 0],
            targets[success, 1],
            targets[success, 2],
            s=46,
            c=max_tilt[success],
            cmap="Blues",
            vmin=0,
            vmax=tilt_limit,
            edgecolors="#111111",
            linewidths=0.25,
            label="满足约束",
            depthshade=True,
        )
        cbar = fig.colorbar(scatter, ax=ax, shrink=0.72, pad=0.08)
        cbar.set_label("最大倾角/(°)")
    ax.scatter([0], [0], [0], s=95, c="#111111", marker="s", label="机械臂基座")
    ax.set_title("采样目标点及约束满足性")
    ax.set_xlabel("$X$/m")
    ax.set_ylabel("$Y$/m")
    ax.set_zlabel("$Z$/m")
    ax.view_init(elev=24, azim=-52)
    ax.grid(True, alpha=0.28)
    ax.legend(loc="upper left", frameon=False)
    save(fig, out_dir, "sampling_constraint_3d")
    plt.close(fig)


def plot_method_comparison(experiments: Sequence[Experiment], out_dir: Path, tilt_limit: float) -> None:
    labels = [exp.label for exp in experiments]
    success_rate = []
    mean_error = []
    max_observed_tilt = []
    smooth_accel = []
    for exp in experiments:
        rows = exp.rows
        ok = successful_rows(rows)
        success_rate.append(100.0 * len(ok) / max(1, len(rows)))
        errors = finite_values(rows, "final_error_m") * 1000.0
        tilts = finite_values(rows, "max_tilt_deg")
        accels = finite_values([row for row in rows if bool(row["planned_success"])], "rms_joint_accel_rad_s2")
        mean_error.append(float(np.mean(errors)) if len(errors) else np.nan)
        max_observed_tilt.append(float(np.max(tilts)) if len(tilts) else np.nan)
        smooth_accel.append(float(np.nanmedian(accels)) if len(accels) else np.nan)

    fig, axes = plt.subplots(1, 4, figsize=(9.2, 2.55), facecolor="white")
    palette = [COLORS["blue"], COLORS["orange"], COLORS["green"]]
    metrics = [
        ("（a）完整成功率", "完整成功率/%", success_rate, (0, 105), None),
        ("（b）平均末端误差", "误差/mm", mean_error, None, 20),
        ("（c）最大观测倾角", "倾角/(°)", max_observed_tilt, None, tilt_limit),
        ("（d）关节加速度", "RMS加速度/(rad·s$^{-2}$)", smooth_accel, None, None),
    ]
    x = np.arange(len(labels))
    for ax, (title, ylabel, values, ylim, ref) in zip(axes, metrics):
        bars = ax.bar(
            x,
            values,
            color=palette[: len(labels)],
            edgecolor="#1f1f1f",
            linewidth=0.55,
            width=0.62,
        )
        ax.set_title(title, pad=4)
        ax.set_ylabel(ylabel)
        if ylim is not None:
            ax.set_ylim(*ylim)
        if ref is not None:
            ax.axhline(ref, color=COLORS["red"], linestyle=(0, (4, 2)), linewidth=1.0)
        ax.grid(axis="y", color="#BFBFBF", alpha=0.35, linestyle="-")
        ax.set_xticks(x)
        ax.set_xticklabels(labels, rotation=18, fontproperties=CHINESE_FONT)
        for bar, value in zip(bars, values):
            if np.isfinite(value):
                if ref is not None and value > ref:
                    bar.set_hatch("//")
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    bar.get_height(),
                    f"{value:.1f}",
                    ha="center",
                    va="bottom",
                    fontsize=7,
                )
    apply_publication_fonts(fig)
    fig.tight_layout(w_pad=1.1)
    save(fig, out_dir, "method_comparison_metrics")
    plt.close(fig)


def plot_tilt_limit_curve(exp: Experiment, out_dir: Path) -> None:
    rows = exp.rows
    errors = np.asarray([float(row["final_error_m"]) for row in rows], dtype=float)
    tilts = np.asarray([float(row["max_tilt_deg"]) for row in rows], dtype=float)
    accurate = np.isfinite(errors) & (errors <= POSITION_TOLERANCE_M)
    finite_tilts = tilts[np.isfinite(tilts) & accurate]
    thresholds = np.linspace(0.0, DEFAULT_TILT_LIMIT_DEG, 91)
    rates = [100.0 * float(np.sum(accurate & np.isfinite(tilts) & (tilts <= th))) / max(1, len(rows)) for th in thresholds]
    minimum_all = float(np.max(finite_tilts)) if len(finite_tilts) else np.nan

    fig, ax = plt.subplots(figsize=(5.6, 3.45), facecolor="white")
    ax.plot(thresholds, rates, color=COLORS["blue"], linewidth=1.6)
    ax.scatter(thresholds[::10], rates[::10], color=COLORS["blue"], s=18, zorder=3)
    if np.isfinite(minimum_all):
        ax.axvline(minimum_all, color=COLORS["red"], linestyle=(0, (4, 2)), linewidth=1.0)
        ax.annotate(
            f"全部有效样本\n最小阈值：{minimum_all:.2f}°",
            xy=(minimum_all, 100.0),
            xytext=(min(DEFAULT_TILT_LIMIT_DEG - 13.0, minimum_all + 4.0), 63.0),
            arrowprops={"arrowstyle": "->", "color": COLORS["red"], "linewidth": 0.8},
            bbox={"boxstyle": "round,pad=0.25", "facecolor": "white", "edgecolor": COLORS["red"]},
            fontsize=7.3,
            color=COLORS["red"],
        )
    ax.axvline(DEFAULT_TILT_LIMIT_DEG, color=COLORS["gray"], linestyle=":", linewidth=1.0)
    ax.set_title("倾角阈值可行性曲线")
    ax.set_xlabel("倾角阈值/(°)")
    ax.set_ylabel("同时满足误差与倾角约束的目标点比例/%")
    ax.set_xlim(0, DEFAULT_TILT_LIMIT_DEG + 1)
    ax.set_ylim(0, 105)
    ax.grid(True, color="#BFBFBF", alpha=0.35)
    save(fig, out_dir, "tilt_limit_feasibility")
    plt.close(fig)


def load_qpos(path: Path) -> List[np.ndarray]:
    data = np.load(path, allow_pickle=True)
    return [np.asarray(item, dtype=float) for item in data["planned_qpos"].tolist()]


def choose_common_target(experiments: Sequence[Experiment]) -> int | None:
    if not experiments:
        return None
    common = {int(row["target_id"]) for row in experiments[0].rows if bool(row["planned_success"])}
    for exp in experiments[1:]:
        common &= {int(row["target_id"]) for row in exp.rows if bool(row["planned_success"])}
    if not common:
        return None
    proposed = experiments[0]
    candidates = [row for row in proposed.rows if int(row["target_id"]) in common and bool(row["sim_success"])]
    if candidates:
        return int(max(candidates, key=lambda row: float(row["max_tilt_deg"]))["target_id"])
    return min(common)


def plot_smoothness_profile(experiments: Sequence[Experiment], out_dir: Path) -> None:
    usable = [exp for exp in experiments if exp.trajectories_path is not None]
    if len(usable) < 2:
        return
    target_id = choose_common_target(usable)
    if target_id is None:
        return
    fig, axes = plt.subplots(2, 1, figsize=(6.2, 4.35), sharex=True, facecolor="white")
    colors = [COLORS["blue"], COLORS["orange"], COLORS["green"]]
    linestyles = ["-", "--", "-."]
    dt = 0.03
    for exp, color, linestyle in zip(usable, colors, linestyles):
        qpos_all = load_qpos(exp.trajectories_path)  # type: ignore[arg-type]
        if target_id >= len(qpos_all):
            continue
        q = np.asarray(qpos_all[target_id], dtype=float)
        if len(q) < 3:
            continue
        speed = np.linalg.norm(np.diff(q, axis=0) / dt, axis=1)
        accel = np.linalg.norm(np.diff(np.diff(q, axis=0) / dt, axis=0) / dt, axis=1)
        axes[0].plot(np.arange(len(speed)), speed, color=color, linestyle=linestyle, linewidth=1.45, label=exp.label)
        axes[1].plot(np.arange(len(accel)), accel, color=color, linestyle=linestyle, linewidth=1.45, label=exp.label)
    axes[0].set_ylabel("关节速度范数\n/(rad·s$^{-1}$)")
    axes[1].set_ylabel("关节加速度范数\n/(rad·s$^{-2}$)")
    axes[1].set_xlabel("轨迹指令序号")
    axes[0].set_title(f"目标点 {target_id} 的关节空间顺滑性")
    for ax in axes:
        ax.grid(True, color="#BFBFBF", alpha=0.35)
        ax.legend(frameon=False, ncol=3, loc="upper right")
    apply_publication_fonts(fig)
    fig.tight_layout()
    save(fig, out_dir, "smoothness_profile")
    plt.close(fig)


def write_summary(experiments: Sequence[Experiment], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "experiment_summary.csv"
    fieldnames = [
        "method",
        "targets",
        "planned_success",
        "sim_success",
        "success_rate_percent",
        "finite_sim_runs",
        "mean_final_error_mm",
        "max_final_error_mm",
        "mean_max_tilt_deg",
        "max_success_tilt_deg",
        "max_observed_tilt_deg",
        "tilt_violation_runs",
        "median_rms_accel_rad_s2",
    ]
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for exp in experiments:
            rows = exp.rows
            ok = successful_rows(rows)
            planned_rows = [row for row in rows if bool(row["planned_success"])]
            finite_rows = [row for row in rows if np.isfinite(float(row["final_error_m"]))]
            errors = finite_values(finite_rows, "final_error_m") * 1000.0
            success_tilts = finite_values(ok, "max_tilt_deg")
            observed_tilts = finite_values(finite_rows, "max_tilt_deg")
            accels = finite_values(planned_rows, "rms_joint_accel_rad_s2")
            tilt_violations = sum(
                1
                for row in finite_rows
                if float(row["final_error_m"]) <= POSITION_TOLERANCE_M
                and np.isfinite(float(row["max_tilt_deg"]))
                and float(row["max_tilt_deg"]) > DEFAULT_TILT_LIMIT_DEG
            )
            writer.writerow(
                {
                    "method": exp.label,
                    "targets": len(rows),
                    "planned_success": len(planned_rows),
                    "sim_success": len(ok),
                    "success_rate_percent": 100.0 * len(ok) / max(1, len(rows)),
                    "finite_sim_runs": len(finite_rows),
                    "mean_final_error_mm": float(np.mean(errors)) if len(errors) else np.nan,
                    "max_final_error_mm": float(np.max(errors)) if len(errors) else np.nan,
                    "mean_max_tilt_deg": float(np.mean(success_tilts)) if len(success_tilts) else np.nan,
                    "max_success_tilt_deg": float(np.max(success_tilts)) if len(success_tilts) else np.nan,
                    "max_observed_tilt_deg": float(np.max(observed_tilts)) if len(observed_tilts) else np.nan,
                    "tilt_violation_runs": tilt_violations,
                    "median_rms_accel_rad_s2": float(np.nanmedian(accels)) if len(accels) else np.nan,
                }
            )
    print(f"saved {path}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--results",
        nargs="+",
        required=True,
        help="One or more results.csv files. Put the proposed method first.",
    )
    parser.add_argument("--out", default="outputs/paper_experiments")
    parser.add_argument("--tilt-limit-deg", type=float, default=DEFAULT_TILT_LIMIT_DEG)
    return parser


def main() -> None:
    args = build_parser().parse_args()
    configure_style()
    experiments = [read_results(Path(path)) for path in args.results]
    out_dir = Path(args.out)
    plot_sampling_constraint_3d(experiments[0], out_dir, args.tilt_limit_deg)
    plot_method_comparison(experiments, out_dir, args.tilt_limit_deg)
    plot_tilt_limit_curve(experiments[0], out_dir)
    plot_smoothness_profile(experiments, out_dir)
    write_summary(experiments, out_dir)


if __name__ == "__main__":
    main()
